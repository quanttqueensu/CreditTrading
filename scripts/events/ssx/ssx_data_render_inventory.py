"""Render the per-table appendix of the full R2 inventory from its CSVs. Offline.

    python3 scripts/events/ssx/ssx_data_render_inventory.py

Reads  results/events/ssx/ssx_data/r2_full_inventory_2026-10-19.csv (+ _columns_)
Writes results/events/ssx/ssx_data/R2_FULL_INVENTORY_TABLES_2026-10-19.md

WHY A SEPARATE STEP
-------------------
`ssx_data_r2_inventory.py` measures the bucket; this only formats what it
measured, so the appendix can be regenerated without the network and cannot
drift from the CSV. 1,146 tables with every column would be an unreadable page
(Compustat `funda` alone has 949 columns), so each table shows its first 30
column names and the count of the rest; the full list is the columns CSV.
Nothing here computes a new number.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[3]
D = REPO / "results" / "events" / "ssx" / "ssx_data"
STAMP = "2026-10-19"
MAX_COLS = 30


def main() -> int:
    t = pd.read_csv(D / f"r2_full_inventory_{STAMP}.csv", dtype={"date_ranges": str})
    c = pd.read_csv(D / f"r2_full_inventory_columns_{STAMP}.csv")
    cols = c.groupby(["schema", "table"]).column.apply(list).to_dict()
    out = [f"# R2 full inventory, per table ({STAMP})", "",
           "Generated by `scripts/events/ssx/ssx_data_render_inventory.py` from the CSVs that "
           "`scripts/events/ssx/ssx_data_r2_inventory.py` wrote (run 2026-10-19 15:25 UTC). "
           "Size is the object size in MB; rows and date ranges come from the parquet footer "
           "(row-group statistics; `NO_STATS` = at least one row group lacks a statistic). "
           "Bucket redacted to `<bucket>`. The narrative is `R2_FULL_INVENTORY_2026-10-19.md`.", ""]
    for schema, g in t.groupby("schema", sort=True):
        out += [f"## `{schema}` ({len(g)} tables, {g.size_mb.sum() / 1e3:.2f} GB)", "",
                "| table | MB | rows | cols | date ranges | first columns |", "|---|---|---|---|---|---|"]
        for _, r in g.sort_values("table").iterrows():
            cl = cols.get((schema, r.table), [])
            shown = ", ".join(cl[:MAX_COLS]) + (f" (+{len(cl) - MAX_COLS} more)" if len(cl) > MAX_COLS else "")
            dr = "" if pd.isna(r.date_ranges) else str(r.date_ranges).replace("|", "/")
            out.append(f"| `{r.table}` | {r.size_mb} | {int(r.rows) if pd.notna(r.rows) else ''} | "
                       f"{r.n_columns} | {dr} | {shown} |")
        out.append("")
    (D / f"R2_FULL_INVENTORY_TABLES_{STAMP}.md").write_text("\n".join(out))
    print(f"wrote {len(t)} tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
